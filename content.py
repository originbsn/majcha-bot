def is_true(value, blank=False):
    v = (value or "").strip().lower()
    if not v:
        return blank
    if v in TRUE_WORDS:
        return True
    if v in FALSE_WORDS:
        return False
    return blank


def parse_date(value):
    """รับ 2026-10-31, 31/10/2026, 31/10/2569 (พ.ศ.) — คืน date หรือ None ถ้าอ่านไม่ออก"""
    v = (value or "").strip()
    if not v:
        return None
    m = re.fullmatch(r"(\d{4})-(\d{1,2})-(\d{1,2})", v)
    if m:
        y, mo, d = int(m.group(1)), int(m.group(2)), int(m.group(3))
    else:
        m = re.fullmatch(r"(\d{1,2})/(\d{1,2})/(\d{4})", v)
        if not m:
            raise ValueError(v)
        d, mo, y = int(m.group(1)), int(m.group(2)), int(m.group(3))
    if y > 2400:
        y -= 543
    return date(y, mo, d)


def promo_status(promo, today):
    """คืน 'active' | 'off' | 'upcoming' | 'expired' | 'bad_date'"""
    if not is_true(promo.get("เปิดใช้"), blank=True):
        return "off"
    try:
        start = parse_date(promo.get("วันเริ่ม"))
        end = parse_date(promo.get("วันสิ้นสุด"))
    except ValueError:
        return "bad_date"
    if start and today < start:
        return "upcoming"
    if end and today > end:
        return "expired"
    return "active"


def info_value(content, key, default=""):
    for row in content["info"]:
        if row.get("หัวข้อ") == key:
            return row.get("รายละเอียด", default) or default
    return default


