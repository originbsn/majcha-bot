def _fetch_tab(tab_name):
    url = (f"https://docs.google.com/spreadsheets/d/{SHEET_ID}/gviz/tq"
           f"?tqx=out:csv&sheet={quote(tab_name)}")
    resp = requests.get(url, timeout=10)
    resp.raise_for_status()
    if "text/csv" not in resp.headers.get("Content-Type", ""):
        # ชีตไม่ได้แชร์ Google จะส่งหน้า login (HTML) กลับมา
        raise ValueError(f'อ่านแท็บ "{tab_name}" ไม่ได้ — เช็กว่าแชร์ชีตแบบทุกคนที่มีลิงก์ดูได้')
    resp.encoding = "utf-8"
    rows = []
    for row in csv.DictReader(io.StringIO(resp.text)):
        row = {(k or "").strip(): (v or "").strip() for k, v in row.items()}
        if any(row.values()):
            rows.append(row)
    return rows


def reload(force=True):
    """ดึงชีตใหม่ คืนค่า (สำเร็จไหม, ข้อความ)"""
    global _content, _loaded_at, _source, _last_error
    with _lock:
        if not force and _content is not None and time.time() - _loaded_at < CACHE_SECONDS:
            return True, "ใช้แคช"
        if not SHEET_ID:
            _content, _source, _loaded_at = DEFAULT_CONTENT, "default", time.time()
            _last_error = "ยังไม่ได้ตั้ง SHEET_ID"
            return False, _last_error
        try:
            fetched = {key: _fetch_tab(name) for key, name in TABS.items()}
            if not fetched["info"] and not fetched["menu"]:
                raise ValueError('แท็บ "ข้อมูลร้าน" และ "เมนู" ว่างทั้งคู่ — ไม่อัปเดต')
            _content, _source, _loaded_at, _last_error = fetched, "sheet", time.time(), ""
            return True, "อัปเดตจากชีตแล้ว"
        except Exception as e:
            _last_error = str(e)
            print(f"Sheet load error: {e}")
            if _content is None:
                _content, _source = DEFAULT_CONTENT, "default"
            # ลองใหม่รอบหน้าแทนที่จะยิงชีตทุกข้อความ
            _loaded_at = time.time()
            return False, _last_error


